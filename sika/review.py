"""Local administrative review commands. Explicit target, OS identity, no API calls."""

import argparse
import json
from pathlib import Path
import subprocess

import sqlalchemy as sa

from sika import publication


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    commands = parser.add_subparsers(dest="command", required=True)
    commands.add_parser("identity", help="Print the OS principal for the operator allowlist")
    for command in ("approve", "publish"):
        child = commands.add_parser(command)
        child.add_argument("--target", type=Path, required=True)
        child.add_argument("--legacy", type=Path)
        child.add_argument("--source-root", type=Path)
        child.add_argument("--release-id", type=int, required=True)
        child.add_argument("--reason", required=True)
        if command == "approve":
            child.add_argument("--quality-run-id", type=int, required=True)
            child.add_argument("--evidence", type=Path, required=True, help="Reviewed JSON; never autogenerated certification")
        else:
            child.add_argument("--approval-id", type=int, required=True, help="Review decision ID returned by approve")
    args = parser.parse_args(argv)
    try:
        if args.command == "identity":
            print(publication.operator_identity())
            return 0
        kwargs = dict(legacy=args.legacy, source_root=args.source_root)
        if args.command == "approve":
            result = publication.approve(args.target, args.release_id, args.quality_run_id, args.reason,
                                         json.loads(args.evidence.read_text(encoding="utf-8")), **kwargs)
        else:
            result = publication.publish(args.target, args.release_id, args.approval_id, args.reason, **kwargs)
        print(json.dumps(result, ensure_ascii=False, indent=2))
        return 0
    except sa.exc.SQLAlchemyError:
        # Driver exceptions may echo complete review JSON/SQL parameters.
        print("REFUSED: Database constraint or service failure; no action committed")
        return 1
    except (ValueError, OSError, subprocess.SubprocessError) as exc:
        print(f"REFUSED: {exc}")
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
